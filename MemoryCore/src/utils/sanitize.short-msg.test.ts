// L1 质量门：短消息不得被误杀（2026-09-25 全量 L0 语料 3341 条实测得出的约束）
//
// 背景：sanitize.ts 里曾有一段长度规则（<2 字符 / >5000 字符）被整段注释掉。
// 本轮用全量真实语料量测「原样恢复」的误伤面，结论是**不能恢复**：
//   · 1 字符仅 4 条（0.12%：「补」「A」「2」），拦掉收益极小
//   · 2-5 字符有 142 条（4.25%），其中大量是真实决策指令——「先做方案一」
//     「继续查找」「查看日志」「立项」「先尝试A」，拦掉即丢用户意图
//   · >5000 字符仅 8 条（0.24%），且全部是 assistant 长报告，提示词本就禁抽助手输出
// 因此那两行保持注释是有原因的，不是漏改。本测试把该结论钉住，防止后来者
// 「顺手修复」造成静默丢数据。
import { describe, expect, it } from "vitest";
import { shouldExtractL1 } from "./sanitize.js";

describe("L1 质量门：短消息保留（2026-09-25 全量语料实证）", () => {
  it("2-5 字符的真实决策指令必须放行（恢复长度规则会误杀这批）", () => {
    for (const t of ["先做方案一", "继续查找", "查看日志", "立项", "先尝试A", "继续开工", "再跑一次"]) {
      expect(shouldExtractL1(t), `不应拦：${t}`).toBe(true);
    }
  });

  it("6-15 字符的有效提问必须放行", () => {
    for (const t of ["你刚刚使用的是什么搜索工具", "WebSearch这个工具在哪", "看看我的记忆", "只能用OpenAI兼容接口吗"]) {
      expect(shouldExtractL1(t), `不应拦：${t}`).toBe(true);
    }
  });

  it("超长真实内容（接近 API 上限）仍放行——按长度拦会丢大段上下文", () => {
    expect(shouldExtractL1("青鸟项目审计表采用 PostgreSQL 原生分区表方案。".repeat(200))).toBe(true);
  });

  it("仍然拦得住纯符号与纯问号（现有规则未回退）", () => {
    // 注意：规则只拦「连续」的符号/问号（/^[^\w\s...]{1,5}$/ 与 /^[?？]+$/），
    // "？ ？" 这类带空格的形态不在覆盖范围内——实测语料中无此形态，不为它加规则。
    for (const t of ["...", "→", "???", "？？？"]) {
      expect(shouldExtractL1(t), `应拦：${t}`).toBe(false);
    }
  });
});
